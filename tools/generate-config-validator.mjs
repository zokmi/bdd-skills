// Development-only generator. Plugin users run the checked-in standalone files.
import fs from 'node:fs';
import Ajv from 'ajv/dist/2020.js';
import standalone from 'ajv/dist/standalone/index.js';
import equal from 'ajv/dist/runtime/equal.js';
import ucs2length from 'ajv/dist/runtime/ucs2length.js';

const schemaDir = new URL('../skills/bdd-local-test/schemas/', import.meta.url);
const outputDir = new URL('../skills/bdd-local-test/scripts/lib/', import.meta.url);
const helpers = { equal: equal.default, ucs2length: ucs2length.default };
function readSchema(name) {
  return JSON.parse(fs.readFileSync(new URL(name + '.schema.json', schemaDir), 'utf8'));
}

const args = process.argv.slice(2);
if (args.length && (args.length !== 1 || args[0] !== '--check')) throw new Error('Expected --check or no arguments');
function emit(filename, source) {
  const target = new URL(filename, outputDir);
  // Inline Ajv's two pure runtime helpers so plugin installation needs no npm step.
  source = source.replace(/require\("ajv\/dist\/runtime\/(equal|ucs2length)"\)\.default/g,
    (_, name) => '(' + helpers[name].toString() + ')');
  if (/require\(/.test(source)) throw new Error('Unexpected runtime dependency in ' + filename);
  source = '// Generated by npm run generate:config-validator; do not edit.\n' +
    '// Ajv and fast-deep-equal: MIT; see config-validator.LICENSE.txt.\n' + source;
  source = source.replace(/\r\n/g, '\n');
  if (args[0] === '--check') {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== source) {
      throw new Error(filename + ' is stale. Run npm run generate:config-validator');
    }
  } else {
    fs.writeFileSync(target, source);
  }
}

const code = { source: true, lines: true, esm: true };
const ajv = new Ajv({ allErrors: true, code });
emit('config-validator.mjs', standalone(ajv, ajv.compile(readSchema('config'))));

// The result schema declares the array types outside its conditional minItems rules.
const assignment = readSchema('assignment');
const result = readSchema('result');
const approvedPlan = readSchema('approved-plan');
const contracts = new Ajv({ schemas: [assignment, result, approvedPlan], strictTypes: false, code });
emit('parallel-validators.mjs', standalone(contracts, {
  assignment: assignment.$id, result: result.$id, approvedPlan: approvedPlan.$id,
}));
