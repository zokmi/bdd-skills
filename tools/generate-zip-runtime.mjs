import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = path.join(root, 'skills/bdd-local-test/scripts/lib');
const check = process.argv[2] === '--check';
const normalize = text => text.replace(/\r\n/g, '\n');
function emit(name, text) {
  const file = path.join(output, name);
  if (check) {
    if (normalize(fs.readFileSync(file, 'utf8')) !== normalize(text)) {
      throw new Error('Regenerate ' + name + ' with npm run generate:zip-runtime');
    }
  } else fs.writeFileSync(file, normalize(text));
}

const result = await build({
  absWorkingDir: root, platform: 'node', format: 'esm', target: 'node18', bundle: true, write: false,
  // Share yazl's copy of the dual-format CRC module with the streaming reader.
  alias: { 'buffer-crc32': createRequire(import.meta.url).resolve('buffer-crc32') },
  stdin: { resolveDir: root, contents: [
    "export { openPromise as openReader } from 'yauzl';",
    "export { ZipFile as ZipWriter } from 'yazl';",
    "import crc32 from 'buffer-crc32';",
    "export const fallbackCrc32 = crc32.unsigned;",
  ].join('\n') },
  banner: { js: [
    '// Generated by npm run generate:zip-runtime. See zip-runtime.LICENSE.txt.',
    "import { createRequire } from 'node:module';",
    'const require = createRequire(import.meta.url);',
  ].join('\n') },
});
emit('zip-runtime.mjs', result.outputFiles[0].text);
const licenses = ['yauzl', 'yazl', 'pend', 'buffer-crc32'].map(name => {
  const dir = path.join(root, 'node_modules', name);
  const { version } = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  return name + ' ' + version + '\n\n' + fs.readFileSync(path.join(dir, 'LICENSE'), 'utf8').trimEnd();
});
emit('zip-runtime.LICENSE.txt', licenses.join('\n\n') + '\n');
