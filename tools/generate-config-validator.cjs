'use strict';

// Development-only generator. Plugin users run the checked-in standalone file.
const fs = require('node:fs');
const path = require('node:path');
const Ajv = require('ajv/dist/2020');
const standalone = require('ajv/dist/standalone');
const schema = require('../skills/bdd-local-test/schemas/config.schema.json');
const args = process.argv.slice(2);
if (args.length && (args.length !== 1 || args[0] !== '--check')) throw new Error('Expected --check or no arguments');
const target = path.resolve(__dirname, '../skills/bdd-local-test/scripts/lib/config-validator.cjs');
const ajv = new Ajv({ allErrors: true, code: { source: true, lines: true } });
let source = standalone(ajv, ajv.compile(schema));
// Inline Ajv's two pure runtime helpers so plugin installation needs no npm step.
source = source.replace(/require\("ajv\/dist\/runtime\/(equal|ucs2length)"\)\.default/g,
  (_, name) => '(' + require('ajv/dist/runtime/' + name).default.toString() + ')');
if (/require\(/.test(source)) throw new Error('Unexpected runtime dependency in standalone validator');
source = '// Generated by npm run generate:config-validator; do not edit.\n' +
  '// Ajv and fast-deep-equal: MIT; see config-validator.LICENSE.txt.\n' + source;
source = source.replace(/\r\n/g, '\n');
if (args[0] === '--check') {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== source) {
    throw new Error('Config validator is stale. Run npm run generate:config-validator');
  }
} else {
  fs.writeFileSync(target, source);
}
